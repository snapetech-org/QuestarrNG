import console from "node:console";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import * as prettier from "prettier";

const root = process.cwd();
const manifestPath = path.join(root, "localization/messages.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const messages = manifest.messages ?? {};
const sourceById = Object.fromEntries(
  Object.entries(messages).map(([id, message]) => [id, message.source])
);
const translationsById = Object.fromEntries(
  Object.entries(messages).map(([id, message]) => [id, message.translations])
);

const serviceIds = JSON.parse(
  await readFile(path.join(root, "localization/service-message-ids.json"), "utf8")
);
if (
  !Array.isArray(serviceIds) ||
  new Set(serviceIds).size !== serviceIds.length ||
  serviceIds.some((id) => typeof id !== "string" || !Object.hasOwn(messages, id))
)
  throw new Error("Invalid service-message ID registry");
const serviceSources = Object.fromEntries(serviceIds.map((id) => [id, messages[id].source]));
const serviceTranslations = Object.fromEntries(
  serviceIds.map((id) => [id, messages[id].translations])
);

const outputs = new Map([
  [
    "shared/service-message-catalog.ts",
    "/** Generated from localization/messages.json and service-message-ids.json. Do not edit directly. */\n" +
      "export const SERVICE_MESSAGE_SOURCES = " +
      JSON.stringify(serviceSources, null, 2) +
      " as const;\n" +
      "export const SERVICE_MESSAGE_TRANSLATIONS = " +
      JSON.stringify(serviceTranslations, null, 2) +
      " as const;\n" +
      "export type ServiceMessageKey = keyof typeof SERVICE_MESSAGE_SOURCES;\n",
  ],
  [
    "client/src/lib/stable-interface-messages.ts",
    "/** Generated from localization/messages.json. Do not edit this file directly. */\n" +
      "export const STABLE_INTERFACE_MESSAGES = " +
      JSON.stringify(sourceById, null, 2) +
      " as const;\n\n" +
      "export type StableInterfaceMessageId = keyof typeof STABLE_INTERFACE_MESSAGES;\n",
  ],
  [
    "client/src/lib/ui-labels.ts",
    "/** Generated from localization/messages.json. Do not edit this file directly. */\n" +
      "export const UI_LABELS = " +
      JSON.stringify(translationsById, null, 2) +
      " as const;\n",
  ],
]);
for (const [relativePath, source] of outputs) {
  const prettierConfig = (await prettier.resolveConfig(path.join(root, relativePath))) ?? {};
  outputs.set(
    relativePath,
    await prettier.format(source, {
      ...prettierConfig,
      filepath: path.join(root, relativePath),
      parser: "typescript",
    })
  );
}

const checkOnly = process.argv.includes("--check");
let failed = false;
for (const [relativePath, expected] of outputs) {
  const filePath = path.join(root, relativePath);
  if (checkOnly) {
    let actual = "";
    try {
      actual = await readFile(filePath, "utf8");
    } catch {
      // Report missing generated outputs through the same stale-catalog message.
    }
    if (actual !== expected) {
      console.error(relativePath + " is stale. Run npm run generate:localization.");
      failed = true;
    }
    continue;
  }
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, expected, "utf8");
}
if (failed) process.exitCode = 1;
