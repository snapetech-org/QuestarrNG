export function getAdditionalApiErrorDetailLabel(
  source: string,
  language: InterfaceLanguage
): string | undefined {
  const localeIndex = API_ERROR_DETAIL_LOCALE_ORDER.indexOf(language);
  if (localeIndex < 0 || !Object.hasOwn(ADDITIONAL_API_ERROR_DETAIL_LABELS, source)) {
    return undefined;
  }
  return ADDITIONAL_API_ERROR_DETAIL_LABELS[source as AdditionalApiErrorDetailSourceMessage][
    localeIndex
  ];
}
